// Serialises a token set to CSS custom properties, Tailwind v4 @theme, W3C
// design-tokens JSON, a Figma variables payload and SCSS.

import { hexToRgb } from './color.ts';
import { SCALE_NAMES } from './scales.ts';
import { refLabel, refVar, type Ref, type ThemeTokens } from './semantic.ts';
import { recipeToCommand, type TokenSet } from './tokens.ts';

export const FORMATS = {
  css: { label: 'CSS variables', file: 'tokens.css' },
  tailwind: { label: 'Tailwind v4', file: 'theme.css' },
  json: { label: 'Design tokens JSON', file: 'tokens.json' },
  figma: { label: 'Figma variables', file: 'figma-variables.json' },
  scss: { label: 'SCSS', file: '_tokens.scss' },
} as const;
export type Format = keyof typeof FORMATS;
export const isFormat = (value: string): value is Format => Object.hasOwn(FORMATS, value);

export function exportTokens(tokens: TokenSet, format: Format): string {
  return { css, tailwind, json, figma, scss }[format](tokens);
}

const header = (t: TokenSet) => `Generated by huecraft. Recreate with: ${recipeToCommand(t.recipe)}`;
const lines = (rows: (string | false)[], indent = '  ') =>
  rows.filter((r): r is string => r !== false).map((r) => (r === '' ? '' : indent + r)).join('\n');

// ---- CSS ----------------------------------------------------------------

const primitiveDecls = (t: TokenSet): string[] => [
  ...SCALE_NAMES.flatMap((name) => t.scales[name].swatches.map((s) => `--color-${name}-${s.step}: ${s.hex};`)),
  '--color-white: #ffffff;',
];
const p3Decls = (t: TokenSet): string[] =>
  SCALE_NAMES.flatMap((name) =>
    t.scales[name].swatches.filter((s) => s.p3).map((s) => `--color-${name}-${s.step}: ${s.p3};`),
  );
const semanticDecls = (theme: ThemeTokens): string[] => [
  ...theme.tokens.map((tok) => `--color-${tok.name}: var(${refVar(tok.ref)});`),
  ...theme.shadows.map((s) => `--shadow-${s.name}: ${s.value};`),
];
// Tailwind v4 pairs a size with its line height as --text-<name>--line-height; the CSS export uses the same names.
const typeDecls = (t: TokenSet): string[] => [
  `--font-sans: ${t.fonts.sans};`,
  `--font-heading: ${t.fonts.heading};`,
  `--font-mono: ${t.fonts.mono};`,
  ...t.type.flatMap((s) => [`--text-${s.name}: ${s.css};`, `--text-${s.name}--line-height: ${s.lineHeight};`]),
];
const dimensionDecls = (t: TokenSet): string[] => [
  ...typeDecls(t),
  ...t.space.map((s) => `--space-${s.name}: ${s.css};`),
  ...t.radius.map((r) => `--radius-${r.name}: ${r.css};`),
];

function css(t: TokenSet): string {
  const dark = semanticDecls(t.themes.dark);
  const p3 = p3Decls(t);
  return `/* ${header(t)} */

:root {
  color-scheme: light;

  /* Color scales */
${lines(primitiveDecls(t))}

  /* Semantic colors, light theme */
${lines(semanticDecls(t.themes.light))}

  /* Type, space, radius */
${lines(dimensionDecls(t))}
}

/* Dark theme: set data-theme="dark" on <html>, or follow the system setting. */
[data-theme="dark"] {
  color-scheme: dark;
${lines(dark)}
}
@media (prefers-color-scheme: dark) {
  :root:not([data-theme="light"]) {
    color-scheme: dark;
${lines(dark, '    ')}
  }
}
${
  p3.length
    ? `
/* Wide-gamut screens get the chroma that sRGB had to give up. */
@media (color-gamut: p3) {
  :root {
${lines(p3, '    ')}
  }
}
`
    : ''
}`;
}

// ---- Tailwind v4 ----------------------------------------------------------

function tailwind(t: TokenSet): string {
  const dark = semanticDecls(t.themes.dark);
  const p3 = p3Decls(t);
  return `/* ${header(t)} */
@import "tailwindcss";

@theme {
${lines(primitiveDecls(t))}

${lines(semanticDecls(t.themes.light))}

${lines(typeDecls(t))}
  --spacing: ${t.space.find((s) => s.name === '1')!.css};
${lines(t.radius.map((r) => `--radius-${r.name}: ${r.css};`))}
}

@layer base {
  [data-theme="dark"] {
    color-scheme: dark;
${lines(dark, '    ')}
  }
${
  p3.length
    ? `  @media (color-gamut: p3) {
    :root {
${lines(p3, '      ')}
    }
  }
`
    : ''
}}
`;
}

// ---- W3C design tokens (DTCG 2025.10) ----------------------------------------

const round = (v: number, places = 4) => Math.round(v * 10 ** places) / 10 ** places;
const dtcgColor = (hex: string) => ({
  $value: { colorSpace: 'srgb', components: hexToRgb(hex).map((v) => round(v)), hex },
});
const dtcgAlias = (ref: Ref) => `{color.${ref === 'white' ? 'white' : `${ref.scale}.${ref.step}`}}`;
const dtcgDimension = (px: number) => ({ $value: { value: round(px / 16), unit: 'rem' } });
const dtcgPx = (value: number) => ({ value, unit: 'px' });

function json(t: TokenSet): string {
  const group = <T>(items: T[], key: (item: T) => string, value: (item: T) => unknown) =>
    Object.fromEntries(items.map((item) => [key(item), value(item)]));
  const doc = {
    $description: header(t),
    color: {
      $type: 'color',
      ...group([...SCALE_NAMES], (n) => n, (n) => group(t.scales[n].swatches, (s) => String(s.step), (s) => ({
        ...dtcgColor(s.hex),
        ...(s.p3 ? { $extensions: { 'huecraft.p3': s.p3 } } : {}),
      }))),
      white: dtcgColor('#ffffff'),
    },
    semantic: group(['light', 'dark'] as const, (name) => name, (name) => ({
      $type: 'color',
      ...group(t.themes[name].tokens, (tok) => tok.name, (tok) => ({ $value: dtcgAlias(tok.ref) })),
    })),
    fontFamily: {
      $type: 'fontFamily',
      ...group(Object.entries(t.fonts), ([name]) => name, ([, stack]: [string, string]) => ({
        $value: stack.split(',').map((f) => f.trim().replace(/^'|'$/g, '')),
      })),
    },
    fontSize: {
      $type: 'dimension',
      $description: 'Values are the desktop sizes; the fluid clamp() is in $extensions.',
      ...group(t.type, (s) => s.name, (s) => ({ ...dtcgDimension(s.maxPx), $extensions: { 'huecraft.fluid': s.css } })),
    },
    lineHeight: {
      $type: 'number',
      $description: 'Unitless, for the fontSize token of the same name.',
      ...group(t.type, (s) => s.name, (s) => ({ $value: s.lineHeight })),
    },
    space: { $type: 'dimension', ...group(t.space, (s) => s.name, (s) => dtcgDimension(s.px)) },
    radius: {
      $type: 'dimension',
      ...group(t.radius, (r) => r.name, (r) => (r.name === 'full' ? { $value: dtcgPx(9999) } : dtcgDimension(r.px))),
    },
    shadow: group(['light', 'dark'] as const, (name) => name, (name) => ({
      $type: 'shadow',
      ...group(t.themes[name].shadows, (s) => s.name, (s) => ({
        $value: s.layers.map((l) => ({
          color: { ...dtcgColor(l.color).$value, alpha: l.alpha },
          offsetX: dtcgPx(0),
          offsetY: dtcgPx(l.y),
          blur: dtcgPx(l.blur),
          spread: dtcgPx(0),
        })),
      })),
    })),
  };
  return JSON.stringify(doc, null, 2) + '\n';
}

// ---- Figma variables (REST API bulk payload) ---------------------------------

function figma(t: TokenSet): string {
  const variables: object[] = [];
  const values: object[] = [];
  const add = (collection: string, name: string, type: 'COLOR' | 'FLOAT' | 'STRING', byMode: [string, unknown][]) => {
    const id = `${collection}/${name}`;
    variables.push({ action: 'CREATE', id, name, variableCollectionId: collection, resolvedType: type });
    for (const [modeId, value] of byMode) values.push({ variableId: id, modeId, value });
  };
  const rgba = (hex: string) => {
    const [r, g, b] = hexToRgb(hex).map((v) => round(v));
    return { r, g, b, a: 1 };
  };
  const primitiveName = (ref: Ref) => (ref === 'white' ? 'white' : `${ref.scale}/${ref.step}`);

  for (const name of SCALE_NAMES) {
    for (const s of t.scales[name].swatches) add('primitives', `${name}/${s.step}`, 'COLOR', [['primitives-value', rgba(s.hex)]]);
  }
  add('primitives', 'white', 'COLOR', [['primitives-value', rgba('#ffffff')]]);
  for (const s of t.type) add('primitives', `font-size/${s.name}`, 'FLOAT', [['primitives-value', round(s.maxPx, 2)]]);
  // Figma line heights are in px, not a multiple of the size.
  for (const s of t.type) add('primitives', `line-height/${s.name}`, 'FLOAT', [['primitives-value', round(s.maxPx * s.lineHeight, 2)]]);
  // A Figma font family is one name, so only a brand font becomes a variable; the system stacks have no equivalent.
  if (t.recipe.font) add('primitives', 'font-family/sans', 'STRING', [['primitives-value', t.recipe.font]]);
  if (t.recipe.heading) add('primitives', 'font-family/heading', 'STRING', [['primitives-value', t.recipe.heading]]);
  // Figma variable names may not contain a dot, so half steps stay as 0_5 and 1_5.
  for (const s of t.space) add('primitives', `space/${s.name}`, 'FLOAT', [['primitives-value', s.px]]);
  for (const r of t.radius) add('primitives', `radius/${r.name}`, 'FLOAT', [['primitives-value', r.px]]);

  const alias = (ref: Ref) => ({ type: 'VARIABLE_ALIAS', id: `primitives/${primitiveName(ref)}` });
  t.themes.light.tokens.forEach((tok, i) =>
    add('semantic', tok.name, 'COLOR', [
      ['semantic-light', alias(tok.ref)],
      ['semantic-dark', alias(t.themes.dark.tokens[i]!.ref)],
    ]),
  );

  return (
    JSON.stringify(
      {
        variableCollections: [
          { action: 'CREATE', id: 'primitives', name: 'Primitives', initialModeId: 'primitives-value' },
          { action: 'CREATE', id: 'semantic', name: 'Semantic', initialModeId: 'semantic-light' },
        ],
        variableModes: [
          { action: 'UPDATE', id: 'primitives-value', name: 'Value', variableCollectionId: 'primitives' },
          { action: 'UPDATE', id: 'semantic-light', name: 'Light', variableCollectionId: 'semantic' },
          { action: 'CREATE', id: 'semantic-dark', name: 'Dark', variableCollectionId: 'semantic' },
        ],
        variables,
        variableModeValues: values,
      },
      null,
      2,
    ) + '\n'
  );
}

// ---- SCSS -------------------------------------------------------------------

function scss(t: TokenSet): string {
  const map = (name: string, rows: string[]) => `$${name}: (\n${lines(rows)}\n);`;
  const scales = SCALE_NAMES.map((name) =>
    map(`color-${name}`, t.scales[name].swatches.map((s) => `${s.step}: ${s.hex},`)),
  );
  const theme = (th: ThemeTokens) =>
    map(`theme-${th.theme}`, [
      ...th.tokens.map((tok) => `'${tok.name}': ${tok.hex}, // ${refLabel(tok.ref)}`),
      ...th.shadows.map((s) => `'shadow-${s.name}': (${s.value}),`),
    ]);
  return `// ${header(t)}

${scales.join('\n')}

${theme(t.themes.light)}
${theme(t.themes.dark)}

$font-sans: ${t.fonts.sans};
$font-heading: ${t.fonts.heading};
$font-mono: ${t.fonts.mono};
${map('text', t.type.map((s) => `'${s.name}': ${s.css},`))}
${map('line-height', t.type.map((s) => `'${s.name}': ${s.lineHeight},`))}
${map('space', t.space.map((s) => `'${s.name.replace('_', '-')}': ${s.css},`))}
${map('radius', t.radius.map((r) => `'${r.name}': ${r.css},`))}
`;
}
